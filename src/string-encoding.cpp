Opal::ErrorCode Opal::Impl::EncodeSingleByte(const HighHalfTable& table, uchar32 in_code_point, ArrayView<char8>& output)
{
    if (output.GetSize() == 0)
    {
        return ErrorCode::InsufficientSpace;
    }
    u32 byte = in_code_point < 0x80 ? in_code_point : 0x100;
    for (u32 i = 0; i < 128 && byte == 0x100; ++i)
    {
        byte = table[i] == in_code_point ? 0x80 + i : byte;
    }
    if (byte == 0x100)
    {
        return ErrorCode::InvalidArgument;
    }
    output[0] = static_cast<char8>(static_cast<u8>(byte));
    output = ArrayView<char8>(output.begin() + 1, output.end());
    return ErrorCode::Success;
}

Opal::ErrorCode Opal::Impl::DecodeSingleByte(const HighHalfTable& table, ArrayView<const char8>& input, uchar32& out_code_point)
{
    if (input.GetSize() == 0)
    {
        return ErrorCode::EndOfString;
    }
    const u8 byte = static_cast<u8>(input[0]);
    const uchar32 code_point = byte < 0x80 ? byte : table[byte - 0x80];
    if (byte >= 0x80 && code_point == 0)
    {
        return ErrorCode::InvalidArgument;
    }
    out_code_point = code_point;
    input = ArrayView<const char8>(input.begin() + 1, input.end());
    return ErrorCode::Success;
}

namespace
{
#if defined(OPAL_PLATFORM_MACOS)
// macOS has no c32rtomb or mbrtoc32, but its wchar_t holds a UTF-32 code point in every locale, which the wide calls take.
size_t CodePointToMultiByte(char* output, char32_t code_point, mbstate_t* state)
{
    return wcrtomb(output, static_cast<wchar_t>(code_point), state);
}

size_t MultiByteToCodePoint(char32_t* output, const char* input, size_t size, mbstate_t* state)
{
    wchar_t wide = 0;
    const size_t count = mbrtowc(&wide, input, size, state);
    if (count <= size)
    {
        *output = static_cast<char32_t>(wide);
    }
    return count;
}
#else
size_t CodePointToMultiByte(char* output, char32_t code_point, mbstate_t* state)
{
    return c32rtomb(output, code_point, state);
}

size_t MultiByteToCodePoint(char32_t* output, const char* input, size_t size, mbstate_t* state)
{
    return mbrtoc32(output, input, size, state);
}
#endif
}  // namespace

Opal::EncodingLocale::EncodingLocale() : m_encoding_state(), m_decoding_state()
{
    OPAL_ASSERT(mbsinit(&m_encoding_state) != 0, "Encoding state is not initialized!");
    OPAL_ASSERT(mbsinit(&m_decoding_state) != 0, "Decoding state is not initialized!");
}

Opal::ErrorCode Opal::EncodingLocale::EncodeOne(CodePointType in_code_point, ArrayView<CodeUnitType>& output)
{
    CodeUnitType buffer[MB_LEN_MAX];
    const mbstate_t saved_state = m_encoding_state;
    const size_t count = CodePointToMultiByte(buffer, in_code_point, &m_encoding_state);
    if (count == static_cast<size_t>(-1))
    {
        m_encoding_state = saved_state;
        return ErrorCode::InvalidArgument;
    }
    if (count > output.GetSize())
    {
        m_encoding_state = saved_state;
        return ErrorCode::InsufficientSpace;
    }
    if (count > 0)
    {
        memcpy(output.GetData(), buffer, count);
        output = ArrayView<CodeUnitType>(output.begin() + static_cast<i64>(count), output.end());
    }
    return ErrorCode::Success;
}

Opal::ErrorCode Opal::EncodingLocale::DecodeOne(ArrayView<const CodeUnitType>& input, CodePointType& out_code_point)
{
    if (input.GetSize() == 0)
    {
        return ErrorCode::EndOfString;
    }
    const size_t count = MultiByteToCodePoint(&out_code_point, input.GetData(), input.GetSize(), &m_decoding_state);
    if (count == 0)
    {
        // We've just written null character
        input = ArrayView<const CodeUnitType>(input.begin() + 1, input.end());
        return ErrorCode::Success;
    }
    if (count == static_cast<size_t>(-1))
    {
        return ErrorCode::InvalidArgument;
    }
    if (count == static_cast<size_t>(-2))
    {
        return ErrorCode::IncompleteSequence;
    }
    if (count == static_cast<size_t>(-3))
    {
        return ErrorCode::Success;
    }
    input = ArrayView<const CodeUnitType>(input.begin() + static_cast<i64>(count), input.end());
    return ErrorCode::Success;
}
